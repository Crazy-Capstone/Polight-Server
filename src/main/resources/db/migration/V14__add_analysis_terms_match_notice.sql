-- 약관을 어떻게 찾았는지와, 그 사실을 사용자에게 알릴 문구를 남긴다.
--
-- 지금까지 매칭 단계(EXACT/REVISION/INSURER/NONE)와 판단 근거는 로그에만 찍고 버렸다.
-- 그래서 화면에서는 "보험사·상품명이 정확히 맞는 약관"과 "상품명은 안 맞지만 그 보험사
-- 약관이 하나뿐이라 고른 것"이 구분되지 않는다. 둘 다 그냥 답변이 나온다.
--
-- 사용자는 그 답을 보고 보험금을 청구하거나 포기한다. 확실하지 않은 근거로 답하고 있다면
-- 그 사실이 화면에 드러나야 한다.

-- 어느 단계에서 찾았는지. AI 서버의 /internal/terms/match 가 돌려주는 level 과 같은 어휘다.
--
-- CHECK 를 걸지 않는다. 어휘의 정본이 AI 쪽에 있어 그쪽이 단계를 하나 늘리는 순간
-- 마이그레이션을 먼저 돌려야 연결이 서게 된다. 값이 지나가는 것보다 그것이 더 나쁘다.
ALTER TABLE analysis_results
    ADD COLUMN terms_match_stage character varying(30);

-- 사용자에게 보여줄 안내. 깔끔하게 맞았으면(EXACT) null 이라 화면에 아무것도 뜨지 않는다.
--
-- 길이를 재지 않고 text 로 둔다. 문구를 다듬는 것은 화면 쪽 사정이라 길이가 오가는데,
-- 그때마다 마이그레이션을 돌리게 할 이유가 없다.
ALTER TABLE analysis_results
    ADD COLUMN terms_match_notice text;

-- 이미 분석이 끝난 행은 두 값이 비어 있다. 되살릴 방법이 없다 -- 매칭을 어떻게 했는지
-- 남겨 두지 않았기 때문이다. 백필(TermsBackfillService)을 돌리면 다시 판단하면서 채워진다.
