--
-- 이 값이 필요한 이유: 선택한 걱정에 해당하는 담보가 목록에 없을 때 "가입하지 않으셨습니다"라고
-- 단정할 수 있는지가 여기서 갈린다. 추출이 일부를 빠뜨린 상태에서 단정하면, 실제로는 보장되는데
-- 안 된다고 오해시켜 사용자가 청구를 포기한다. 그게 가장 나쁜 실패다.
--
-- 판단은 추출한 쪽만 할 수 있어 AI 서버가 콜백으로 보내준다. 다만 현재 에이전트 출력으로는
-- AI 쪽도 원본 표의 행 수를 알 수 없어, 당분간 항상 false 로 온다. 값이 켜지는 시점에
-- 백엔드 코드는 바뀌지 않는다 -- 받아서 저장하고 되돌려주기만 한다.
ALTER TABLE analysis_results
    ADD COLUMN coverages_complete boolean NOT NULL DEFAULT false;
