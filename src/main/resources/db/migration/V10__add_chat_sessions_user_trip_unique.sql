-- 챗봇 세션은 여행당 하나다.
--
-- 프론트에 세션 목록·전환·"새 대화" UI가 없다. 챗봇은 하단 탭 하나이고 여행 컨텍스트도
-- 인자로 받지 않으므로, 사용자가 여러 세션을 구분해 쓸 방법 자체가 없다. 그래서 서버가
-- 여행당 하나를 확보해 재사용한다.
--
-- 애플리케이션 코드의 findByUserIdAndTripId + 없으면 생성만으로는 부족하다. 같은 여행에
-- 첫 질문이 동시에 들어오면 둘 다 조회에서 빈 결과를 받아 두 개를 만든다. 그 뒤로는
-- 조회가 어느 쪽을 집을지 알 수 없어 대화가 두 갈래로 갈린다. 이 인덱스가 한쪽을 막고,
-- 막힌 쪽은 다시 조회해 이미 만들어진 세션을 쓴다.
--
-- trip_id 가 nullable 이라 부분 인덱스로 둔다. Postgres 는 NULL 을 서로 다른 값으로 보므로
-- 조건이 없으면 trip_id IS NULL 인 행에는 제약이 걸리지 않는다. 여행 없는 세션을 만드는
-- 경로는 아직 없지만, 생기더라도 이 인덱스가 막지 않도록 범위를 명시한다.
CREATE UNIQUE INDEX uk_chat_sessions_user_trip
    ON chat_sessions (user_id, trip_id)
    WHERE trip_id IS NOT NULL;
