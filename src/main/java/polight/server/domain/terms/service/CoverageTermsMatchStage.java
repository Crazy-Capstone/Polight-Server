package polight.server.domain.terms.service;

/** 가입 담보를 약관의 보장 규칙에 어떻게 붙였는지. 곧 그 연결을 얼마나 믿을 수 있는지다. */
public enum CoverageTermsMatchStage {

  /** 표기 차이를 걷어낸 담보명이 규칙명과 완전히 같았다. */
  EXACT,

  /**
   * 증권 담보명이 규칙명에 수식어를 덧붙인 형태였다. 예: 규칙 "상해의료비" ← 담보 "해외여행중 상해의료비(3천만원)".
   *
   * <p>증권은 같은 보장을 적용 범위나 가입금액과 함께 인쇄하는 일이 많아 이름이 약관보다 길어진다. 반대 방향(규칙명이 담보명보다 긴 경우)은 붙이지
   * 않는다 -- 그것은 약관이 더 좁은 보장을 말하는 것이라, 사용자가 산 것보다 좁은 조건을 씌우게 된다.
   */
  QUALIFIED,

  /** 붙이지 않았다. 맞는 규칙이 없거나, 둘 이상이라 어느 것인지 가릴 수 없었다. */
  NONE
}
