package polight.server.domain.terms.service;

/**
 * 가입 담보를 약관의 보장 규칙에 어떻게 붙였는지. 곧 그 연결을 얼마나 믿을 수 있는지다.
 *
 * <p>선언 순서가 곧 신뢰도 순서이고, 연결도 그 순서로 시도한다. 위에서 붙으면 아래는 보지 않는다.
 */
public enum CoverageTermsMatchStage {

  /** 표기 차이를 걷어낸 담보명이 규칙명과 완전히 같았다. */
  EXACT,

  /**
   * 증권 담보명이 규칙명에 수식어를 덧붙인 형태였다. 예: 규칙 "상해의료비" ← 담보 "해외여행중 상해의료비(3천만원)".
   *
   * <p>증권은 같은 보장을 적용 범위나 가입금액과 함께 인쇄하는 일이 많아 이름이 약관보다 길어진다. 반대 방향(규칙명이 담보명보다 긴 경우)은 붙이지
   * 않는다 -- 그것은 약관이 더 좁은 보장을 말하는 것이라, 사용자가 산 것보다 좁은 조건을 씌우게 된다.
   */
  QUALIFIED,

  /**
   * 이름으로는 못 붙었고, 표준 분류({@code category})가 같은 규칙이 그 약관에 딱 하나였다.
   *
   * <p>이름이 서로 너무 다른 경우를 위한 마지막 수단이다 -- 증권 "해외의료실비보장"과 약관 "기본형 해외여행 실손의료비"는 같은 보장인데 글자가
   * 겹치지 않아 위 두 단계로는 영영 붙지 않는다.
   *
   * <p><b>category는 식별자가 아니라 분류값이다.</b> 여러 담보와 여러 규칙이 같은 값을 공유하라고 만든 것이라, 후보가 하나로 좁혀질 때만
   * 근거가 된다. 그래서 이름으로 못 붙은 경우에만, 후보가 정확히 1건일 때만 쓴다.
   */
  CATEGORY,

  /** 붙이지 않았다. 사유는 {@link CoverageTermsUnlinkReason}가 갖는다. */
  NONE
}
