package polight.server.domain.terms.service;

/**
 * 약관을 어느 단계에서 찾아냈는지. 곧 그 연결을 얼마나 믿을 수 있는지다.
 *
 * <p>연결 자체는 {@code analysis_results.matched_terms_id} 하나로 남지만, 어떻게 찾았는지는 남지 않는다. 근거 조항을 화면에
 * 보여주거나 챗봇 답변에 인용할 때 신뢰도를 함께 판단해야 해서 호출부에 이 값을 돌려준다.
 */
public enum TermsMatchStage {

  /** 보험사와 상품명이 (표기 차이를 걷어내고) 모두 일치하는 약관이 하나뿐이었다. 가장 믿을 만하다. */
  EXACT,

  /** 보험사·상품명이 같은 약관이 여럿(개정판)이라, 증권이 적용받았을 시점을 기준으로 하나를 골랐다. */
  REVISION,

  /**
   * 상품명은 맞지 않았지만 그 보험사에 등록된 약관이 딱 하나여서 그것으로 연결했다.
   *
   * <p>가장 약한 단계다. 그 보험사의 다른 상품 약관이 아직 등록되지 않았을 뿐인데 하나뿐이라 골랐을 수 있다. 이 단계로 연결된 약관은 담보별 조항 인용처럼
   * 정확도가 중요한 곳에서 그대로 쓰기 전에 한 번 더 따져야 한다.
   */
  INSURER,

  /**
   * 연결하지 않았다.
   *
   * <p>실패가 아니라 정상 흐름의 한 갈래다. 등록되지 않은 상품이거나, 후보가 여럿이라 어느 것인지 가릴 수 없었다는 뜻이다. 애매한 후보를 붙이는 것보다
   * 비워 두는 편이 낫다 -- 다른 상품의 약관을 근거로 "보장되지 않습니다"라고 답하면 사용자는 받을 수 있는 보험금을 포기한다.
   */
  NONE
}
