package polight.server.domain.terms.service;

/**
 * 담보에 약관 규칙을 붙이지 못한 사유.
 *
 * <p>사유를 나누는 이유는 <b>고쳐야 할 사람이 다르기 때문</b>이다. 후보가 없는 것은 약관 규칙을 더 적재하면 되는 일이고, 가릴 수 없는 것은
 * 적재된 데이터 자체가 어긋났다는 뜻이다. 사유 없이 담보명만 모아 두면 드물고 심각한 후자가 흔하고 무해한 전자 더미에 묻힌다.
 */
public enum CoverageTermsUnlinkReason {

  /** 맞는 규칙이 없었다. 그 보장의 규칙이 아직 적재되지 않았다는 뜻이다. */
  NOT_FOUND,

  /**
   * 이름으로 맞는 규칙이 둘 이상이라 어느 것인지 가릴 수 없었다.
   *
   * <p>한 약관 안에 같은 이름의 규칙이 둘 있다는 뜻이라 적재 결함에 가깝다. <b>이때 category 폴백을 타지 않는다</b> -- 이름으로 못 가린
   * 것을 더 거친 분류로 가를 수는 없고, 그렇게 고른 하나는 사실상 동전 던지기다.
   */
  AMBIGUOUS_TITLE,

  /** 같은 분류의 규칙이 둘 이상이라 가릴 수 없었다. category는 원래 여럿이 공유하는 값이라 드문 일이 아니다. */
  AMBIGUOUS_CATEGORY
}
