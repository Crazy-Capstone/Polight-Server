package polight.server.domain.terms.service;

/**
 * 백필이 무엇을 대상으로 삼고 어디까지 다시 판단할지.
 *
 * <p>둘을 나눠야 하는 이유는 두 판단의 성격이 다르기 때문이다. "이 증권은 어느 약관인가"는 보험사·상품명에서 나오는 것이라 자주 바뀌지 않지만,
 * "이 담보는 어느 규칙인가"는 규칙을 적재하거나 매칭 단계를 늘릴 때마다 결과가 달라진다.
 */
public enum TermsBackfillMode {

  /**
   * 약관이 붙지 않은 분석만. 기본값이다.
   *
   * <p>약관 저장소가 생기기 전에 끝난 분석을 회수하는 용도다.
   */
  MISSING_TERMS,

  /**
   * 완료된 증권 분석 전부. <b>약관 연결은 그대로 두고 담보 규칙만 다시 붙인다.</b>
   *
   * <p>보장 규칙을 새로 적재했거나 담보 매칭 단계를 늘린 뒤에 쓴다. 이때 회수해야 할 것은 대부분 "약관은 이미 붙었는데 규칙이 안 붙은" 분석인데,
   * {@link #MISSING_TERMS}는 그것들을 대상에서 통째로 빼기 때문에 이 모드가 따로 필요하다.
   */
  RELINK_COVERAGES,

  /**
   * 완료된 증권 분석 전부. 약관까지 다시 판단한다.
   *
   * <p>약관을 새로 적재했거나 약관 매칭 규칙을 고쳤을 때만 쓴다. <b>이전에 붙었던 연결이 끊길 수 있다</b> -- 그 약관이 지워졌거나, 이제 후보가
   * 여럿이라 가릴 수 없게 된 경우다.
   */
  REMATCH;

  /** 이미 약관이 붙은 분석도 대상으로 삼는지. */
  boolean includesLinked() {
    return this != MISSING_TERMS;
  }

  /** 붙어 있는 약관 연결을 다시 판단하는지. */
  boolean rematchesTerms() {
    return this == REMATCH;
  }
}
